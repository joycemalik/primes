import os
"""
Compare Gemini Primes and Prime Vector Pairs
============================================

Compares the first 250 vectors generated by geminiPrimes and prime_vector_pairs.
Assumes both produce a list of [a, b] pairs of 0/1 values.
"""
import importlib.util
import sys

# Import prime_vector_pairs from the original file
def import_prime_vector_pairs():
    spec = importlib.util.spec_from_file_location("prime_vector_pairs", os.path.join(os.path.dirname(os.path.abspath(__file__)), "prime_vector_pairs.py"))
    module = importlib.util.module_from_spec(spec)
    sys.modules["prime_vector_pairs"] = module
    spec.loader.exec_module(module)
    return module.prime_vector_pairs

# Import geminiPrimes vector generator (assume function is named gemini_prime_vectors)
def import_gemini_prime_vectors():
    spec = importlib.util.spec_from_file_location("geminiPrimes", os.path.join(os.path.dirname(os.path.abspath(__file__)), "gemini_pairs_2adic_kick.py"))
    module = importlib.util.module_from_spec(spec)
    sys.modules["geminiPrimes"] = module
    spec.loader.exec_module(module)
    # Try to find a function that returns the vectors
    if hasattr(module, 'gemini_prime_vectors'):
        return module.gemini_prime_vectors
    elif hasattr(module, 'generate_gemini_vectors'):
        return module.generate_gemini_vectors
    else:
        raise AttributeError("No suitable vector generator found in geminiPrimes.py")

def compare_vectors(vec1, vec2):
    errors = []
    for i, (a, b) in enumerate(zip(vec1, vec2), 1):
        if a != b:
            errors.append((i, a, b))
    return errors

def main():
    n = 250
    print(f"Comparing first {n} vectors from geminiPrimes and prime_vector_pairs...")
    
    # Get original vectors
    prime_vector_func = import_prime_vector_pairs()
    original_vectors = prime_vector_func(n)
    
    # Get gemini vectors
    gemini_vector_func = import_gemini_prime_vectors()
    gemini_vectors = gemini_vector_func(n)
    
    # Compare
    errors = compare_vectors(original_vectors, gemini_vectors)
    
    if not errors:
        print(f"✅ All {n} vectors match perfectly!")
    else:
        print(f"❌ {len(errors)} mismatches found:")
        for idx, orig, gem in errors[:10]:  # Show first 10 errors
            print(f"  At position {idx}: original={orig}, gemini={gem}")
        if len(errors) > 10:
            print(f"  ...and {len(errors)-10} more mismatches.")

if __name__ == "__main__":
    main()
